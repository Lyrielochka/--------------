import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {xy} from '../src/bagrationMapData.js';
const source=JSON.parse(readFileSync('artifacts/sources/minsk-region-osm.json','utf8'));
const relation=source.elements.find(e=>e.type==='relation'&&e.id===59752);
const nodes=new Map(source.elements.filter(e=>e.type==='node').map(n=>[n.id,[n.lon,n.lat]]));
const ways=new Map(source.elements.filter(e=>e.type==='way').map(w=>[w.id,w.nodes]));
function rings(role){
  const remaining=new Map(relation.members.filter(m=>m.type==='way'&&m.role===role).map(m=>[m.ref,[...ways.get(m.ref)]]));
  const result=[];
  while(remaining.size){const [id,first]=remaining.entries().next().value;remaining.delete(id);const ring=[...first];
    while(ring[0]!==ring.at(-1)){
      const match=[...remaining].find(([,ids])=>ids[0]===ring.at(-1)||ids.at(-1)===ring.at(-1));
      assert.ok(match,`Unclosed ${role} ring at node ${ring.at(-1)}`);
      const [nextId,ids]=match;remaining.delete(nextId);if(ids.at(-1)===ring.at(-1))ids.reverse();ring.push(...ids.slice(1));
    }
    result.push(ring.map(id=>{assert.ok(nodes.has(id));return nodes.get(id)}));
  }
  return result;
}
const outer=rings('outer'),inner=rings('inner');
function contains(ring,[x,y]){let inside=false;for(let i=0,j=ring.length-1;i<ring.length;j=i++){const [a,b]=ring[i],[c,d]=ring[j];if((b>y)!==(d>y)&&x<(c-a)*(y-b)/(d-b)+a)inside=!inside}return inside}
const polygons=outer.map(r=>[r,...inner.filter(h=>contains(r,h[0]))]);
assert.equal(polygons.reduce((n,p)=>n+p.length-1,0),inner.length);
const geometry={type:'MultiPolygon',coordinates:polygons};
const geojson={type:'Feature',properties:{name:'Минская область',source:'OpenStreetMap contributors',relation:59752,version:relation.version,osmTimestamp:relation.timestamp,downloaded:'2026-10-18',license:'ODbL-1.0',url:'https://www.openstreetmap.org/relation/59752'},geometry};
writeFileSync('public/data/minsk-region.geojson',JSON.stringify(geojson));
const path=polygons.flatMap(p=>p.map(r=>r.map(([lon,lat],i)=>{const p=xy(lon,lat);return `${i?'L':'M'}${p.x.toFixed(3)} ${p.y.toFixed(3)}`}).join(' ')+'Z')).join(' ');
const all=outer.flat().map(([lon,lat])=>xy(lon,lat));
const bounds={left:Math.min(...all.map(p=>p.x)),right:Math.max(...all.map(p=>p.x)),top:Math.min(...all.map(p=>p.y)),bottom:Math.max(...all.map(p=>p.y))};
writeFileSync('src/minskRegionShape.js',`// Generated by scripts/prepare-minsk-region.mjs from OSM relation 59752.\n// Geographic data: OpenStreetMap contributors, ODbL-1.0. Projection matches bagrationMapData.xy.\nexport const minskRegionBounds=${JSON.stringify(bounds)};\nexport const minskRegionPath=${JSON.stringify(path)};\nexport const minskRegionSource=${JSON.stringify(geojson.properties)};\n`);
console.log(JSON.stringify({bounds,outerRings:outer.length,innerRings:inner.length,vertices:polygons.flat(2).length,version:relation.version,timestamp:relation.timestamp}));

writeFileSync('src/minskRegionBounds.js',`// Generated from the same OSM boundary as minskRegionShape.js.\nexport const minskRegionBounds=${JSON.stringify(bounds)};\n`);
